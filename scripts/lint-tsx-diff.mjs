#!/usr/bin/env node
/**
 * lint-tsx-diff.mjs — Run the Strata DS validator against every TSX/JSX
 * file changed in the current PR (or against an explicit file list).
 *
 * Uses the same validator that the MCP server's
 * `validate_component_against_rules` tool exposes. Single source of truth
 * for what counts as a violation.
 *
 * Usage:
 *   npm run lint:tsx-diff                     # diff vs origin/main
 *   npm run lint:tsx-diff -- --base develop   # diff vs origin/develop
 *   npm run lint:tsx-diff -- file1.tsx ...    # explicit files
 *
 * Exit codes:
 *   0  no errors found
 *   1  at least one error found
 *   2  invocation problem (missing file, git error, etc.)
 */

import { execSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateCode, formatValidation } from '../src/mcp-server/validator.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');

function parseArgs(argv) {
  const args = { base: 'origin/main', files: [], help: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--help' || a === '-h') args.help = true;
    else if (a === '--base') { args.base = argv[++i]; }
    else if (a.startsWith('--base=')) { args.base = a.slice('--base='.length); }
    else if (!a.startsWith('--')) args.files.push(a);
  }
  return args;
}

function help() {
  console.log(`Usage: lint-tsx-diff.mjs [--base <ref>] [files...]

Without files, scans every .tsx / .jsx file changed in the diff against the
given base branch (defaults to origin/main).

Examples:
  node scripts/lint-tsx-diff.mjs
  node scripts/lint-tsx-diff.mjs --base develop
  node scripts/lint-tsx-diff.mjs src/components/foo.tsx
`);
}

function gitDiffFiles(base) {
  try {
    const out = execSync(`git diff --name-only --diff-filter=ACMR ${base}...HEAD`, {
      cwd: REPO_ROOT,
      encoding: 'utf8',
    });
    return out.split('\n').map((l) => l.trim()).filter(Boolean);
  } catch (e) {
    console.error(`git diff failed: ${e.message}`);
    process.exit(2);
  }
}

function shouldLint(filePath) {
  if (!/\.(tsx|jsx)$/.test(filePath)) return false;
  // Exclude tests, stories, examples generated by the build
  if (/\.test\.|\.spec\.|__tests__|\.stories\./.test(filePath)) return false;
  // Exclude the DS app preview registry (huge mock content)
  if (/src\/app\/views\/componentPreviews\.tsx$/.test(filePath)) return false;
  return true;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) { help(); return; }

  let files = args.files.length ? args.files : gitDiffFiles(args.base).filter(shouldLint);
  if (files.length === 0) {
    console.log('No TSX/JSX files to lint.');
    return;
  }

  let totalErrors = 0;
  let totalWarnings = 0;
  let totalInfos = 0;
  const reports = [];

  for (const f of files) {
    const absPath = resolve(REPO_ROOT, f);
    if (!existsSync(absPath)) {
      console.warn(`(skipping missing) ${f}`);
      continue;
    }
    const code = readFileSync(absPath, 'utf8');
    const result = validateCode(code, f);
    totalErrors += result.summary.errors;
    totalWarnings += result.summary.warnings;
    totalInfos += result.summary.infos;
    if (result.violations.length > 0) {
      reports.push({ file: f, result });
    }
  }

  console.log(`# Strata DS — TSX diff lint`);
  console.log('');
  console.log(`Files scanned: ${files.length}`);
  console.log(`Files with violations: ${reports.length}`);
  console.log(`Totals: ${totalErrors} error(s) · ${totalWarnings} warning(s) · ${totalInfos} info(s)`);
  console.log('');

  for (const r of reports) {
    console.log(`---`);
    console.log(`## ${r.file}`);
    console.log('');
    console.log(formatValidation(r.result));
    console.log('');
  }

  if (totalErrors > 0) {
    console.log(`Exiting with code 1 because ${totalErrors} error(s) were found.`);
    process.exit(1);
  }
  console.log('✅ No errors in changed TSX/JSX files.');
}

main();
