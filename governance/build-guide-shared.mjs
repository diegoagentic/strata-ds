/**
 * slugify — converts a heading text to a stable URL slug.
 *
 * Used by BOTH the marked renderer (to slug each <h2>/<h3>) and by the
 * example data file (to key example entries). Must produce identical
 * output for both call sites or the injection misses.
 *
 * Examples:
 *   "LAW 1 — Never hardcode hex values or raw colors"
 *     → "law-1-never-hardcode-hex-values-or-raw-colors"
 *   "ERROR 02 — Hardcoded container backgrounds"
 *     → "error-02-hardcoded-container-backgrounds"
 *   "1. Primary action button (CTA)"
 *     → "1-primary-action-button-cta"
 */
export function slugify(s) {
  return String(s)
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-');
}
